local function loadConfigTable(path)
    local loader, loadError = loadfile(path)
    if not loader then return nil, loadError end
    local ok, value = pcall(loader)
    if not ok or type(value) ~= "table" then
        return nil, ok and "Config did not return a table" or tostring(value)
    end
    return value
end

local function preserveLocalConfig(manifest)
    local stagedPath = fs.combine(ONLINE_UPDATE_STAGE, "config.lua")
    local defaults, err = loadConfigTable(stagedPath)
    if not defaults then return nil, "Downloaded config is invalid: " .. tostring(err) end
    if tostring(defaults.version or "") ~= manifest.version then
        return nil, "Downloaded config version does not match the manifest"
    end

    local merged = util.copy(defaults)
    for key, value in pairs(config) do
        if key ~= "version" then merged[key] = util.copy(value) end
    end
    merged.version = manifest.version
    util.writeFile(stagedPath,
        "-- PUMPE configuration. Local settings are preserved during updates.\n"
        .. "return " .. textutils.serialize(merged, { compact = false }) .. "\n")
    return true
end

local function checkForOnlineUpdate()
    if config.auto_update == false then
        onlineUpdateStatus = "DISABLED"
        onlineUpdateColor = colors.lightGray
        return false
    end
    local manifestUrl = tostring(config.update_manifest_url or "")
    if manifestUrl == "" then
        onlineUpdateStatus = "URL NOT CONFIGURED"
        onlineUpdateColor = colors.lightGray
        return false
    end

    onlineUpdateStatus = "CHECKING INTERNET"
    onlineUpdateColor = colors.orange
    local manifest, err = onlineUpdate.fetchManifest(
        manifestUrl, ONLINE_UPDATE_FILES, config.update_channel or "stable")
    if not manifest then
        onlineUpdateStatus = "CHECK FAILED"
        onlineUpdateColor = colors.red
        if err ~= lastOnlineUpdateError then
            logActivity("Online update: " .. tostring(err), colors.red)
            lastOnlineUpdateError = err
        end
        return false
    end
    lastOnlineUpdateError = nil

    if not onlineUpdate.isNewer(manifest.version, config.version) then
        onlineUpdateStatus = "CURRENT v" .. config.version
        onlineUpdateColor = colors.lime
        return false
    end

    onlineUpdateStatus = "DOWNLOADING v" .. manifest.version
    onlineUpdateColor = colors.cyan
    logActivity("Online update found: v" .. manifest.version, colors.cyan)
    local downloaded, downloadError = onlineUpdate.downloadRelease(
        manifest, manifestUrl, ONLINE_UPDATE_STAGE,
        function(_, index, total)
            onlineUpdateStatus = "DOWNLOADING " .. index .. "/" .. total
        end)
    if not downloaded then
        onlineUpdateStatus = "DOWNLOAD FAILED"
        onlineUpdateColor = colors.red
        logActivity("Online update failed: " .. tostring(downloadError), colors.red)
        return false
    end

    local preserved, preserveError = preserveLocalConfig(manifest)
    if not preserved then
        if fs.exists(ONLINE_UPDATE_STAGE) then fs.delete(ONLINE_UPDATE_STAGE) end
        onlineUpdateStatus = "CONFIG REJECTED"
        onlineUpdateColor = colors.red
        logActivity("Online update failed: " .. tostring(preserveError), colors.red)
        return false
    end

    onlineUpdateStatus = "INSTALLING v" .. manifest.version
    onlineUpdateColor = colors.orange
    local downloadedInstaller =
        util.readFile(fs.combine(ONLINE_UPDATE_STAGE, "startup.lua"))
    local committed, commitError = onlineUpdate.commitRelease(
        manifest, ONLINE_UPDATE_STAGE, ROOT, ONLINE_UPDATE_BACKUP)
    if not committed then
        onlineUpdateStatus = "ROLLED BACK"
        onlineUpdateColor = colors.red
        logActivity("Online update rolled back: " .. tostring(commitError), colors.red)
        return false
    end

    local startupReady, startupWarning = ensureBankStartup(downloadedInstaller)
    if not startupReady then
        logActivity(startupWarning, colors.orange)
    end
    util.writeFile(BANK_RESTART_MARKER, tostring(manifest.version))
    pcall(save)
    onlineUpdateStatus = "RESTARTING v" .. manifest.version
    onlineUpdateColor = colors.lime
    logActivity("Online update installed; restarting", colors.lime)
    sleep(0.1)
    os.reboot()
    return true
end

local function serverLoop()
    while running do
        local sender, message = rednet.receive(config.protocol, 1)
        if sender then route(sender, message) end
    end
end

local function deploymentLoop()
    while running do
        local sender, message = rednet.receive(DEPLOY_PROTOCOL, 1)
        if sender then
            local ok, err = pcall(deploymentRoute, sender, message)
            if not ok then
                logActivity("Deployment error: " .. tostring(err), colors.red)
                if type(message) == "table" and message.request_id then
                    deploymentError(sender, message.request_id, "DEPLOY_ERROR",
                        "Bank deployment service failed")
                end
            end
        end
    end
end

local function schedulerLoop()
    local nextBorderRepair = 0
    while running do
        cleanupEphemeral()
        processSubscriptions()
        if util.nowMs() >= nextBorderRepair then
            repairBorderDepot()
            nextBorderRepair = util.nowMs() + 30 * 1000
        end
        sleep(10)
    end
end

local function onlineUpdateLoop()
    while running do
        checkForOnlineUpdate()
        local interval = math.max(5,
            math.floor(tonumber(config.update_check_seconds) or 10))
        sleep(interval)
    end
end

local function count(map)
    local value = 0
    for _ in pairs(map) do value = value + 1 end
    return value
end

local function dashboardLoop()
    local target = term.current()
    local blink = true
    while running do
        local width, height = target.getSize()
        ui.clear(target)
        ui.header(target, "PUMPE BANK SERVER", "v" .. config.version,
            util.formatClock(blink))
        ui.text(target, 2, 5, "LIVE NETWORK", colors.lime)
        ui.card(target, 2, 7, math.floor((width - 5) / 2), 4, colors.cyan)
        ui.text(target, 4, 8, "ACCOUNTS", colors.lightGray, colors.gray)
        ui.text(target, 4, 9, tostring(count(state.accounts)), colors.white, colors.gray)
        local rightX = math.floor((width - 5) / 2) + 4
        ui.card(target, rightX, 7, width - rightX, 4, colors.magenta)
        ui.text(target, rightX + 2, 8, "TRANSACTIONS", colors.lightGray, colors.gray)
        ui.text(target, rightX + 2, 9, tostring(#state.transactions), colors.white, colors.gray)
        ui.text(target, 2, 11,
            ui.truncate("ONLINE UPDATE  " .. onlineUpdateStatus, width - 2),
            onlineUpdateColor)

        local scene = ui.scene(target)
        local feedY = 12
        ui.text(target, 2, feedY, "ACTIVITY", colors.lightGray)
        local maxFeed = math.max(1, height - feedY - 3)
        for index = 1, math.min(#activity, maxFeed) do
            local item = activity[index]
            ui.text(target, 2, feedY + index,
                item.time .. "  " .. ui.truncate(item.text, width - 10), item.color)
        end
        scene:button("save", width - 18, height - 1, 8, 1, "SAVE",
            { background = colors.blue })
        scene:button("stop", width - 9, height - 1, 8, 1, "STOP",
            { background = colors.red })
        local action = scene:wait({ tickRate = 0.5, flash = false })
        blink = not blink
        if action == "save" then
            save()
            logActivity("Manual save complete", colors.lime)
        elseif action == "stop" then
            if ui.confirm(target, "STOP SERVER", "Save and shut down?", "STOP", "BACK") then
                running = false
                save()
                return
            end
        elseif action == "__terminate" then
            running = false
            save()
            return
        end
    end
end

