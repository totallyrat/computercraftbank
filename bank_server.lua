        output[#output + 1] = {
            event_id = event.event_id,
            title = event.title,
            description = event.description,
            location = event.location,
            event_day = event.event_day,
            event_time = event.event_time,
            sold = sold,
            total = total,
            from_price = minimum,
        }
    end
    return { events = output }
